import 'dart:ffi' as ffi;

/// 2D coordinate representing one corner of a detected barcode.
final class CBarcodePoint extends ffi.Struct {
  @ffi.Double()
  external double x;

  @ffi.Double()
  external double y;
}

/// Single decoded barcode result allocated on the native heap.
final class CBarcodeResult extends ffi.Struct {
  /// Null-terminated UTF-8 decoded string.
  external ffi.Pointer<ffi.Char> text;

  /// Raw payload bytes.
  external ffi.Pointer<ffi.Uint8> raw_bytes;

  /// Number of bytes in `raw_bytes`.
  @ffi.Int32()
  external int raw_bytes_length;

  /// Four localization corner points (topLeft, topRight, bottomRight, bottomLeft).
  @ffi.Array.multi([4])
  external ffi.Array<CBarcodePoint> corner_points;

  /// Number of populated corner points (typically 4).
  @ffi.Int32()
  external int corner_points_count;

  /// Detected barcode format enum (`CBarcodeFormat`).
  @ffi.Int32()
  external int format;

  /// 1 if valid, 0 otherwise.
  @ffi.Int32()
  external int is_valid;
}

/// Contiguous list of decoded barcode results returned across FFI.
final class CBarcodeResultList extends ffi.Struct {
  /// Pointer to array of `CBarcodeResult` of length `count`.
  external ffi.Pointer<CBarcodeResult> results;

  /// Number of detected barcodes.
  @ffi.Int32()
  external int count;

  /// Optional null-terminated error description if decoding threw an exception.
  external ffi.Pointer<ffi.Char> error_message;
}

/// Raw RGBA8888 pixel buffer generated by `zxing_encode_barcode`.
final class CEncodedBarcodeImage extends ffi.Struct {
  /// Pointer to RGBA8888 pixel buffer (`width * height * 4` bytes).
  external ffi.Pointer<ffi.Uint8> rgba_bytes;

  /// Total byte length (`width * height * 4`).
  @ffi.Int32()
  external int byte_length;

  /// Output image width in pixels.
  @ffi.Int32()
  external int width;

  /// Output image height in pixels.
  @ffi.Int32()
  external int height;

  /// Optional null-terminated error message on failure.
  external ffi.Pointer<ffi.Char> error_message;
}

/// FFI bindings to the native `zxing_ffi_bridge` shared library.
class ZxingFfiBindings {
  /// Creates bindings backed by [dynamicLibrary].
  ZxingFfiBindings(ffi.DynamicLibrary dynamicLibrary)
    : _lookup = dynamicLibrary.lookup;

  final ffi.Pointer<T> Function<T extends ffi.NativeType>(String symbolName)
  _lookup;

  /// Returns the underlying engine version string.
  ffi.Pointer<ffi.Char> zxing_engine_version() {
    return _zxing_engine_version();
  }

  late final _zxing_engine_versionPtr =
      _lookup<ffi.NativeFunction<ffi.Pointer<ffi.Char> Function()>>(
        'zxing_engine_version',
      );
  late final _zxing_engine_version = _zxing_engine_versionPtr
      .asFunction<ffi.Pointer<ffi.Char> Function()>();

  /// Decodes one or more barcodes from raw pixel bytes.
  ffi.Pointer<CBarcodeResultList> zxing_decode_image_bytes(
    ffi.Pointer<ffi.Uint8> pixels,
    int width,
    int height,
    int row_stride,
    int pixel_format,
    int try_harder,
    int try_rotate,
    int try_invert,
  ) {
    return _zxing_decode_image_bytes(
      pixels,
      width,
      height,
      row_stride,
      pixel_format,
      try_harder,
      try_rotate,
      try_invert,
    );
  }

  late final _zxing_decode_image_bytesPtr =
      _lookup<
        ffi.NativeFunction<
          ffi.Pointer<CBarcodeResultList> Function(
            ffi.Pointer<ffi.Uint8>,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
          )
        >
      >('zxing_decode_image_bytes');
  late final _zxing_decode_image_bytes = _zxing_decode_image_bytesPtr
      .asFunction<
        ffi.Pointer<CBarcodeResultList> Function(
          ffi.Pointer<ffi.Uint8>,
          int,
          int,
          int,
          int,
          int,
          int,
          int,
        )
      >();

  /// Frees a `CBarcodeResultList` and all nested heap buffers.
  void free_barcode_results(ffi.Pointer<CBarcodeResultList> list) {
    return _free_barcode_results(list);
  }

  late final _free_barcode_resultsPtr =
      _lookup<
        ffi.NativeFunction<ffi.Void Function(ffi.Pointer<CBarcodeResultList>)>
      >('free_barcode_results');
  late final _free_barcode_results = _free_barcode_resultsPtr
      .asFunction<void Function(ffi.Pointer<CBarcodeResultList>)>();

  /// Encodes a UTF-8 string into an RGBA8888 barcode pixel buffer.
  ffi.Pointer<CEncodedBarcodeImage> zxing_encode_barcode(
    ffi.Pointer<ffi.Char> content,
    int width,
    int height,
    int margin,
    int ecc_level,
  ) {
    return _zxing_encode_barcode(content, width, height, margin, ecc_level);
  }

  late final _zxing_encode_barcodePtr =
      _lookup<
        ffi.NativeFunction<
          ffi.Pointer<CEncodedBarcodeImage> Function(
            ffi.Pointer<ffi.Char>,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
            ffi.Int32,
          )
        >
      >('zxing_encode_barcode');
  late final _zxing_encode_barcode = _zxing_encode_barcodePtr
      .asFunction<
        ffi.Pointer<CEncodedBarcodeImage> Function(
          ffi.Pointer<ffi.Char>,
          int,
          int,
          int,
          int,
        )
      >();

  /// Frees a `CEncodedBarcodeImage` and its `rgba_bytes` / `error_message` buffers.
  void free_encoded_barcode_image(ffi.Pointer<CEncodedBarcodeImage> image) {
    return _free_encoded_barcode_image(image);
  }

  late final _free_encoded_barcode_imagePtr =
      _lookup<
        ffi.NativeFunction<ffi.Void Function(ffi.Pointer<CEncodedBarcodeImage>)>
      >('free_encoded_barcode_image');
  late final _free_encoded_barcode_image = _free_encoded_barcode_imagePtr
      .asFunction<void Function(ffi.Pointer<CEncodedBarcodeImage>)>();
}
